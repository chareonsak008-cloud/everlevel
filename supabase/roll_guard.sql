-- เลขฐาน 36 (มีเครื่องหมายลบได้) → int · ผิดรูปแบบ = null
create or replace function public._b36(t text)
returns int language plpgsql immutable as $$
declare neg boolean := false; v bigint := 0; c int; ch text;
begin
  if t is null or t = '' then return null; end if;
  if left(t, 1) = '-' then neg := true; t := substr(t, 2); end if;
  if t = '' or t !~ '^[0-9a-z]{1,6}$' then return null; end if;
  foreach ch in array regexp_split_to_array(t, '') loop
    c := position(ch in '0123456789abcdefghijklmnopqrstuvwxyz') - 1;
    v := v * 36 + c;
  end loop;
  return (case when neg then -v else v end)::int;
end $$;

-- ตรวจคีย์ไอเทมหนึ่งชิ้น: ตีบวก 0–10 · ค่าสุ่มอยู่ในช่วง · ไม่ซ้ำช่อง · ไม่เกิน 6 ค่า
create or replace function public._key_ok(k text)
returns boolean language plpgsql stable set search_path = public as $$
declare b text; ref text; r text; seg text; idx int; v int; n int := 0; seen int[] := '{}'; lo int; hi int;
begin
  if k is null or position('*' in k) = 0 then return true; end if;
  b := split_part(k, '*', 1); ref := split_part(k, '*', 2); r := split_part(k, '*', 4);
  if ref <> '' and (ref !~ '^[0-9]{1,2}$' or ref::int > 10) then return false; end if;
  if split_part(k, '*', 5) <> '' then return false; end if;
  if r = '' or r = '~' then return true; end if;
  foreach seg in array string_to_array(r, '.') loop
    if seg !~ '^[0-9a-z]-?[0-9a-z]{1,6}$' then return false; end if;
    idx := public._b36(left(seg, 1)); v := public._b36(substr(seg, 2));
    if idx is null or v is null or idx = any(seen) then return false; end if;
    select x.lo, x.hi into lo, hi from item_rolls x where x.id = b and x.i = idx;
    if not found or v < lo or v > hi then return false; end if;
    seen := seen || idx; n := n + 1;
  end loop;
  return n between 1 and 6;
end $$;

-- มูลค่ารวม (เดิม) + นับของที่ค่าสุ่มปลอมเป็นค่าผิดปกติ
create or replace function public._wealth(d jsonb, st jsonb, out wealth bigint, out unknown int, out bad int)
language plpgsql stable set search_path = public as $$
declare items jsonb := '[]'::jsonb;
begin
  if jsonb_typeof(d->'player'->'inventory') = 'array' then items := items || (d->'player'->'inventory'); end if;
  if jsonb_typeof(st) = 'array' then items := items || st; end if;
  if jsonb_typeof(d->'player'->'equip') = 'object' then
    items := items || coalesce((select jsonb_agg(jsonb_build_array(v, 1)) from jsonb_each_text(d->'player'->'equip') x(k, v) where v is not null and v <> ''), '[]'::jsonb);
  end if;
  select coalesce(sum(coalesce(c.price, 0) * x.q), 0),
         count(*) filter (where c.id is null),
         count(*) filter (where x.q < 0 or x.q > 999 or not public._key_ok(x.k))
    into wealth, unknown, bad
  from (
    select e->>0 as k, split_part(e->>0, '*', 1) as b,
           case when (e->>1) ~ '^-?[0-9]{1,9}$' then (e->>1)::bigint else 0 end as q
    from jsonb_array_elements(items) e
    where jsonb_typeof(e) = 'array' and left(coalesce(e->>0, '_'), 1) <> '_'
  ) x left join item_catalog c on c.id = x.b;
  wealth := wealth + public._zeny(d);
  if public._zeny(d) > 999999999 then bad := bad + 1; end if;
end $$;

-- ของที่จะลงตลาด / วางบนโต๊ะแลก (เดิม) + ตรวจค่าสุ่ม
create or replace function public._offer_items(p_items jsonb)
returns jsonb language plpgsql stable set search_path = public as $$
declare e jsonb; out jsonb := '[]'::jsonb; q bigint; b text;
begin
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) > 10 then raise exception 'bad_items'; end if;
  for e in select * from jsonb_array_elements(p_items) loop
    if jsonb_typeof(e) <> 'array' or (e->>1) !~ '^[0-9]{1,3}$' then raise exception 'bad_items'; end if;
    q := (e->>1)::bigint; b := split_part(e->>0, '*', 1);
    if q < 1 or q > 999 then raise exception 'bad_items'; end if;
    if not exists (select 1 from item_catalog where id = b and tradable) then raise exception 'untradable:%', e->>0; end if;
    if not public._key_ok(e->>0) then raise exception 'bad_roll:%', e->>0; end if;
    out := out || jsonb_build_array(jsonb_build_array(e->>0, q));
  end loop;
  return out;
end $$;

